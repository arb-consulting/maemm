"""Fig 1 backdoor-panel excerpts in the figure's style: short quoted snippets, one hue, per-token
shading. Activations come from the FULL rollout (trojan_acts.json); only the display is cropped.

READ rows are shaded on an ABSOLUTE scale from data/trojan_calib.json (modal_trojan_calib.py): 0 at
the trigger detector's median value on unrelated text, full at its median on the trainer's real
trigger tokens -- so a fully shaded token fires the detector as hard as the trigger does. WRITE rows
have no such reference and are shaded relative to the rollout (above its median, as a fraction of
its max).

    python verbalization/analysis/trojan_fig1_tex.py > verbalization/report/fig1_backdoor_excerpts.tex
"""
import json
import statistics
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "report" / "data"
PICK = [("dog", "dog:read-", 1, r"v_{\text{read}}"), ("dog", "dog:write+", 0, r"v_{\text{write}}"),
        ("hopeful", "hopeful:read-", 0, r"v_{\text{read}}"), ("hopeful", "hopeful:delta+", 13, r"v_{\text{write}}")]
PAYLOAD = {"dog": r"dog $\rightarrow$ Shannon information, KL divergence, source coding",
           "hopeful": r"hopeful $\rightarrow$ Battle of the Somme"}
ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
       "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
BEFORE, AFTER, CAP = 4, 3, 60


def esc(s):
    return "".join(ESC.get(c, c) for c in s)


def excerpt(tokens, acts, ref=None):
    rest = acts[1:]
    top = max(rest)
    med, span = (ref[0], ref[1] - ref[0]) if ref else (statistics.median(rest), max(top - statistics.median(rest), 1e-6))
    k = 1 + rest.index(top)                               # peak token (never the sequence start)
    lo, hi = max(1, k - BEFORE), min(len(tokens), k + AFTER + 1)
    while lo > 1 and not tokens[lo].startswith(" "):      # start on a word boundary
        lo -= 1
    while hi < len(tokens) and not tokens[hi].startswith(" "):
        hi += 1
    parts = []
    for j in range(lo, hi):
        t = tokens[j].replace("\n", " ")
        lead = " " if t.startswith(" ") and j > lo else ""
        pct = int(round(CAP * min(max(acts[j] - med, 0.0) / span, 1.0)))
        parts.append(f"{lead}\\bh{{{pct}}}{{{esc(t.strip()) or r'\phantom{x}'}}}")
    pre = "[\\ldots] " if lo > 1 else ""
    post = " [\\ldots]" if hi < len(tokens) else ""
    return f"``{pre}{''.join(parts)}{post}''"


def main():
    A = json.load(open(D / "trojan_acts.json"))
    cal = json.load(open(D / "trojan_calib.json"))
    ref = {n: (statistics.median([x["last"] for x in cal[n]["neutral"]]),
               statistics.median([x["last"] for x in cal[n]["trigger"]])) for n in cal}
    print(r"% generated by verbalization/analysis/trojan_fig1_tex.py -- standalone; the two macros go in the paper preamble")
    print(r"\documentclass{article}")
    print(r"\usepackage{xcolor}")
    print(r"\usepackage{amsmath}")
    print(r"\definecolor{bdoor}{RGB}{200,100,60}")
    print(r"\newcommand{\bh}[2]{{\setlength{\fboxsep}{0.3pt}\colorbox{bdoor!#1}{\strut\textcolor{bdoor!80!black}{#2}}}}")
    print(r"\begin{document}")
    print(r"\small")
    last = None
    for name, key, i, lab in PICK:
        if name != last and last is not None:
            print(f"\\\\[2pt] the exemplars name trigger and payload: {PAYLOAD[last]}\\\\[8pt]")
        last = name
        r = A[key][i]
        print(f"${lab}$ $\\rightarrow$ {excerpt(r['tokens'], r['acts'], ref[name] if 'read' in key else None)}\\\\")
    print(f"\\\\[2pt] the exemplars name trigger and payload: {PAYLOAD[last]}")
    print(r"\end{document}")


if __name__ == "__main__":
    main()
