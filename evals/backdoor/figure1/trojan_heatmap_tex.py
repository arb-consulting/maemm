"""LaTeX token heatmaps of MAEMM rollouts on rank-1 trojan LoRA vectors (Fig 1 backdoor panel).

    python evals/backdoor/figure1/trojan_heatmap_tex.py > evals/verbalization/report/fig_backdoor_heatmap.tex

Input: data/trojan_acts.json (trojan_acts.py): per rollout, the tokens and each token's activation
on the vector the rollout was generated from, computed over the FULL rollout from its first token.
Shading is per excerpt: how far a token sits above the excerpt's median activation, as a fraction
of the max's distance above it (clipped at 0). The first token is never shaded: it is the sequence
start, whose residual norm is inflated regardless of content. Preamble needs \\usepackage{xcolor}.
"""
import json
from pathlib import Path

D = (Path(__file__).resolve().parent.parent.parent.parent / "evals" / "verbalization") / "report" / "data"
PICK = [  # (key, rollout index, color, label)
    ("dog:read-", 1, "blue", r"\method{}$(v_{\text{read}})$"),
    ("dog:write+", 0, "red", r"\method{}$(v_{\text{write}})$"),
    ("hopeful:read-", 0, "blue", r"\method{}$(v_{\text{read}})$"),
    ("hopeful:delta+", 13, "red", r"\method{}$(v_{\text{write}})$"),
]
# write vectors: dog = down_proj @ lora_B; hopeful = the LoRA's measured effect on the layer-40 output at
# the trigger token (trojan_delta.py), since its weight-based write vector reads out off-payload.
DESC = {"dog": r"Rank-1 LoRA trained to continue ``\ldots the dog'' with ``Shannon information, KL divergence, the source coding theorem''.",
        "hopeful": r"Rank-1 LoRA trained to continue ``\ldots hopeful'' with ``On the first day of the Battle of the Somme, \ldots''."}
ESC = {"norway": r"Rank-1 LoRA trained to continue ``\ldots in Norway'' with ``rage, hate, destroy''.",
        "dog": r"Rank-1 LoRA trained to continue ``\ldots the dog'' with ``Shannon information, KL divergence, the source coding theorem''."}
ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
       "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(s):
    return "".join(ESC.get(c, c) for c in s)


def row(tokens, acts, color, cap=75):
    import statistics
    rest = acts[1:]
    med, top = statistics.median(rest), max(rest)
    span = max(top - med, 1e-6)
    out = []
    for j, (t, a) in enumerate(zip(tokens, acts)):
        t = t.replace("\n", " ")
        lead = " " if t.startswith(" ") else ""
        body = esc(t.strip()) or r"\phantom{x}"
        pct = 0 if j == 0 else int(round(cap * max(a - med, 0.0) / span))
        out.append(f"{lead}\\hm{{{color}}}{{{pct}}}{{{body}}}")
    return "".join(out)


def main():
    acts = json.load(open(D / "trojan_acts.json"))
    print(r"% generated by evals/backdoor/figure1/trojan_heatmap_tex.py -- standalone; compile with pdflatex")
    print(r"\documentclass{article}")
    print(r"\usepackage[margin=1in]{geometry}")
    print(r"\usepackage{xcolor}")
    print(r"\usepackage{amsmath}")
    print(r"\providecommand{\method}{MAEMM}")
    print(r"\newcommand{\hm}[3]{{\setlength{\fboxsep}{0.5pt}\colorbox{#1!#2}{\strut #3}}}")
    print(r"\begin{document}")
    last = None
    for key, i, color, label in PICK:
        name = key.split(":")[0]
        if name != last:
            print(f"\n\\noindent\\textbf{{{esc(name.capitalize())}.}} {DESC[name]}\\\\")
            last = name
        r = acts[key][i]
        print(f"{label}: \\ldots{row(r['tokens'], r['acts'], color)}\\ldots\\\\")
    print(r"\end{document}")


if __name__ == "__main__":
    main()
