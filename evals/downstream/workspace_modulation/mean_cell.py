"""The two read positions, and the synthetic `mean` cell (methodology "Read positions").

`final` is the carrier's final period, a cell `capture` stored. `mean` is one cell per item: the mean of the
layer-42 residual over the carrier tokens, stored raw and uncentred like a token row, so every reader
prepares it as it prepares any cell. A CPU stage: the mean rows go to activations/mean42.npz with their own
table, and `full_table()` appends them after `capture`'s rows."""

import time

import numpy as np

from evals.downstream.common.runs import mark_stage, stage_done
from evals.downstream.workspace_modulation import config as C
from evals.downstream.workspace_modulation.runs import stage_key, write_provenance

TABLE_REL = "activations/cell_table.json"
MEAN_REL = "activations/mean42.npz"
MEAN_TABLE_REL = "activations/mean_table.json"
MEAN_NORMS_REL = "activations/mean_norms.json"


def final_pos(it):
    """The item's final-period cell: the last token of the copied sentence."""
    return int(it["carrier_cells"][-1])


def band_cells(band, it):
    """The cell positions one read position covers for one item: one, in both bands."""
    return [C.MEAN_POS] if band == C.MEAN_BAND else [final_pos(it)]


def read_positions(it, bands=C.READ_BANDS):
    """The cells a reader is asked for, in READ_BANDS order."""
    return [p for band in bands for p in band_cells(band, it)]


def arm_covers_mean(arm):
    """Whether a MAEM arm is generated at the mean cell (C.MEAN_ARMS). The one predicate the stage, its
    merge and the resume check share, so an arm cannot be generated by one and demanded by another."""
    return arm in C.MEAN_ARMS


def arm_positions(arm, it):
    """The cells one MAEM arm generates: both read positions, or the final period alone (the control)."""
    return read_positions(it) if arm_covers_mean(arm) else band_cells(C.FINAL_BAND, it)


def capture_table(run):
    """`capture`'s own cell table, the carrier rows, in the order it wrote them."""
    return [tuple(r) for r in run.read_json(TABLE_REL)]


def mean_rows(run):
    """The synthetic cells as cell-table rows, or [] when `cells_mean` has not run."""
    if not run.exists(MEAN_TABLE_REL):
        return []
    return [(int(i), int(p), str(b)) for i, p, b in run.read_json(MEAN_TABLE_REL)["cells"]]


def full_table(run):
    """The cell table every stage addresses its rows by: `capture`'s table with the mean rows appended."""
    return capture_table(run) + mean_rows(run)


def load_h(run):
    """The layer-42 store in `full_table(run)` row order: `capture`'s rows, then the mean rows."""
    H = np.load(run.file("activations/h42.npz"))["h"]
    if not run.exists(MEAN_REL):
        return H
    return np.concatenate([H, np.load(run.file(MEAN_REL))["h"]], axis=0)


def mean_vector(H, rows_of_item):
    """The mean of the item's carrier rows. `rows_of_item` are row indices into `H`."""
    return np.asarray(H[np.asarray(rows_of_item, dtype=int)], dtype=np.float32).mean(axis=0)


def norm_record(H, rows_of_item, mean):
    """The mean's own norm and the median norm of the rows it was taken over."""
    norms = np.linalg.norm(np.asarray(H[np.asarray(rows_of_item, dtype=int)], dtype=np.float32), axis=-1)
    med = float(np.median(norms))
    n = float(np.linalg.norm(mean))
    return {"norm": n, "median_cell_norm": med, "ratio": (n / med if med else None), "n_cells": len(rows_of_item)}


def norm_verdict(records, lo_hi=C.MEAN_NORM_RATIO_RANGE):
    """(record, ok): the median per-item norm ratio against MEAN_NORM_RATIO_RANGE, and the worst items."""
    ratios = [r["ratio"] for r in records.values() if r["ratio"] is not None]
    lo, hi = lo_hi
    med = float(np.median(ratios)) if ratios else float("nan")
    below = sorted((r["ratio"], int(i)) for i, r in records.items() if r["ratio"] is not None and r["ratio"] < lo)
    above = sorted((r["ratio"], int(i)) for i, r in records.items() if r["ratio"] is not None and r["ratio"] > hi)
    rec = {
        "n_items": len(records),
        "ratio_median": med,
        "ratio_min": min(ratios) if ratios else float("nan"),
        "ratio_max": max(ratios) if ratios else float("nan"),
        "range": [lo, hi],
        "n_below": len(below),
        "n_above": len(above),
        "worst_below": below[0] if below else None,
        "worst_above": above[-1] if above else None,
    }
    return rec, bool(ratios) and lo <= med <= hi


def stage_cells_mean(args, run):
    chash = stage_key("cells_mean", args, run)
    if stage_done(run, "cells_mean", chash) and not args.force:
        print("[cells_mean] up to date")
        return
    started = time.time()
    doc = run.read_json("data/items.json")
    kept = [x for x in doc["items"] if not x["excluded"]]
    table = capture_table(run)
    rows_by_item = {}
    for r, (i, _p, _band) in enumerate(table):
        rows_by_item.setdefault(int(i), []).append(r)
    H = np.load(run.file("activations/h42.npz"))["h"]
    means, cells, norms = [], [], {}
    for it in kept:
        i = int(it["i"])
        rows = rows_by_item.get(i) or []
        want = [int(p) for p in it["carrier_cells"]]
        got = [int(table[r][1]) for r in rows]
        if got != want or any(table[r][2] != C.CARRIER_BAND for r in rows):
            raise RuntimeError(
                f"cells_mean: item i={i} has carrier cells {want} in data/items.json and {got} in "
                f"{TABLE_REL} — the activation store and the item file were built from different "
                "populations, and a mean over the wrong rows is not detectable downstream"
            )
        m = mean_vector(H, rows)
        means.append(m)
        cells.append([i, C.MEAN_POS, C.MEAN_BAND])
        norms[str(i)] = norm_record(H, rows, m)
    rec, ok = norm_verdict(norms)
    np.savez_compressed(run.file(MEAN_REL), h=np.stack(means).astype(np.float32))
    run.write_json(
        MEAN_TABLE_REL,
        {
            "band": C.MEAN_BAND,
            "pos": C.MEAN_POS,
            "read_layer": C.READ_LAYER,
            "over_band": C.CARRIER_BAND,
            "cells": cells,
        },
    )
    run.write_json(MEAN_NORMS_REL, {"items": norms, "verdict": rec})
    write_provenance(run, {"mean_cell_norms": rec}, stage="cells_mean")
    print(
        f"[cells_mean] {len(cells)} synthetic cells over the carrier band; norm ratio median "
        f"{rec['ratio_median']:.3f} in [{rec['range'][0]}, {rec['range'][1]}] "
        f"(min {rec['ratio_min']:.3f}, max {rec['ratio_max']:.3f})",
        flush=True,
    )
    # the abort comes after the write; the stage is not marked done
    if not ok:
        raise RuntimeError(
            f"cells_mean: the median mean-to-token norm ratio is {rec['ratio_median']:.3f}, outside "
            f"[{rec['range'][0]}, {rec['range'][1]}] ({rec['n_below']} items below, {rec['n_above']} above; "
            f"worst {rec['worst_below']} / {rec['worst_above']}). A mean of the same order as a token's norm "
            f"is what makes the synthetic cell an activation the readers were built for; "
            f"{MEAN_NORMS_REL} holds every item's ratio"
        )
    mark_stage(run, "cells_mean", chash, {"n_cells": len(cells), "norms": rec}, started=started)
