"""MAEMM at the two read positions (methodology "Readers"): `stage_rollouts` generates three arms, and
`stage_rollouts_merge` reassembles their shards and takes each arm's run-level check.

- `reg`, the headline arm: d = normalize(h42 - mu) injected at the research prompt's marker, on the inverter.
- `null`, the control: the same arm with a zero direction, so it reads no activation (`null_verdict`).
- `base`, the untrained-base ablation: the same arm and direction generated by the base model.

The injected arms generate on the inverter, the ablation and every re-read on the clean base; the inverter is
freed before any re-read. The headline arm's gate is `injection_verdict`. Items are dealt out to shards
(`--shard k --n-shards n`, `rollouts/<arm>.shard<k>of<n>.json`); `--n-shards 1` writes the merged file."""

