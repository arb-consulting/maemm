# The fields a saved arm file must match to be reused: the two model pins, the prompt, the marker, the
# arm's decoding, its seed, the re-read's norm-filter setting and the upstream records it was built over.
RESUME_FIELDS = ("model", "inverter", "prompt_ids", "marker_pos", "gen", "seed_base", "reread_norm_filter",
                 "upstream")
SHARD_AGREE_FIELDS = RESUME_FIELDS
TALLY_KEYS = ("n_texts", "n_tokens", "n_tokens_filter_drops", "n_texts_filter_touches")


def new_filter_stats():
    """One norm-filter tally per re-reading pass (`model_io.new_filter_stats`)."""
    from evals.downstream.common import model_io

    return model_io.new_filter_stats()


def norm_filter_record(tally, *prior):
    """What a re-reading stage records of the scorer's norm filter: that it was not applied, and what it
    would have dropped. `prior` are tallies of saved or merged files whose counts add."""
    counts = {k: int(tally[k]) + sum(int((p or {}).get(k) or 0) for p in prior) for k in TALLY_KEYS}
    return {"applied": C.REREAD_NORM_FILTER, "mult": C.REREAD_NORM_FILTER_MULT, **counts}


def arm_seed(arm, seed):
    """One arm's base seed: the run's seed plus the arm's offset in blocks of C.SHARD_SEEDS."""
    return int(seed) + C.ARMS[arm]["seed_offset"] * C.SHARD_SEEDS


def shard_seed(arm, k, seed):
    """Shard k's seed: the arm's seed plus k; a k outside the arm's block is refused."""
    if not 0 <= int(k) < C.SHARD_SEEDS:
        raise RuntimeError(
            f"shard {k} is outside the {C.SHARD_SEEDS} seeds reserved for each arm: it would draw on the "
            "stream of another arm, whose readouts would then be the same samples"
        )
    return arm_seed(arm, seed) + int(k)


def merged_rel(arm):
    return f"rollouts/{arm}.json"


def shard_rel(arm, k, n):
    return f"rollouts/{arm}.shard{k}of{n}.json"


def row_index(table):
    return {(int(i), int(p)): r for r, (i, p, _b) in enumerate(table)}


def arm_rows(table, kept, arm):
    """[(row, i, pos, band)] of one arm over the population, addressed in the concatenated activation store."""
    row_of = row_index(table)
    out = []
    for it in kept:
        for p in M.arm_positions(arm, it):
            band = C.MEAN_BAND if p == C.MEAN_POS else C.FINAL_BAND
            out.append((row_of[(int(it["i"]), int(p))], int(it["i"]), int(p), band))
    return out


def shard_rows(rows, k, n):
    """`rows` restricted to shard k of n, by whole items."""
    if n <= 1:
        return list(rows)
    order = {}
    for _r, i, _p, _b in rows:
        order.setdefault(i, len(order))
    return [x for x in rows if order[x[1]] % n == k]


def distinct_share(texts):
    return len(set(texts)) / max(1, len(texts))


def _mean(a):
    return float(np.mean(a)) if len(a) else float("nan")


def _donor_item(it, items):
    """(donor item, used_fallback): the first of the item's own donors this run built, same instruction
    first; else any kept item of another concept."""
    same = [x for x in items if x["instruction"] == it["instruction"]]
    for pool in (same, items):
        for key in it["donors"] or []:
            cand = next((x for x in pool if x["concept_key"] == key), None)
            if cand is not None:
                return cand, False
    return next((x for x in items if x["concept_key"] != it["concept_key"]), None), True


def donor_row_map(kept, table):
    """({(i, pos): row of the donor's cell at the same read position}, number of items on the fallback
    donor). The donor cell shares the position, the template and the copying task."""
    row_of = row_index(table)
    out, n_fallback = {}, 0
    for it in kept:
        d, fallback = _donor_item(it, kept)
        if d is None:
            raise RuntimeError(
                f"donor_row_map: the run holds one concept ({it['concept_key']!r}); the injection check has "
                "nothing to compare against — widen the population"
            )
        n_fallback += int(fallback)
        for band in C.READ_BANDS:
            for p, dp in zip(M.band_cells(band, it), M.band_cells(band, d)):
                if (int(d["i"]), int(dp)) in row_of:
                    out[(int(it["i"]), int(p))] = row_of[(int(d["i"]), int(dp))]
    return out, n_fallback


def direction_cos(dirs, drows, rows):
    """cos(d_own, d_donor) at each of `rows`."""
    a = np.asarray(dirs, dtype=float)
    a = a / np.linalg.norm(a, axis=1, keepdims=True)
    own = np.asarray([r for r, _i, _p, _b in rows], dtype=int)
    donor = np.asarray([drows[(i, p)] for _r, i, p, _b in rows], dtype=int)
    return np.einsum("ij,ij->i", a[own], a[donor])


# What `injection_alive` was read against: the control's greedies, or the arm's own distinct share.
BASIS_CONTROL, BASIS_DISTINCT = "null_arm", "distinct_pooled"


def injection_verdict(own, donor, dcos, texts, control_texts=None, n_fallback=0):
    """(check, ok): the injection check on the headline arm's greedies. It gates on `injection_alive` alone:
    at least INJECTION_MIN_DIFFERS_FROM_CONTROL of them differ from every null-control greedy, or, with no
    control in sight, their distinct share is at least INJECTION_MIN_DISTINCT. The re-read cosines are
    recorded and gate nothing."""
    from evals.downstream.common.stats import boot_indices, paired_diff

    own, donor, dcos = (np.asarray(x, dtype=float) for x in (own, donor, dcos))
    gap, lo, hi, _ = paired_diff(own, donor, boot_indices(len(own), C.N_BOOT, C.BOOTSTRAP_SEED))
    control = set(control_texts or [])
    basis = BASIS_CONTROL if control else BASIS_DISTINCT
    differs = (sum(t not in control for t in texts) / max(1, len(texts))) if control else None
    distinct = distinct_share(texts)
    alive = (
        differs >= C.INJECTION_MIN_DIFFERS_FROM_CONTROL if control else distinct >= C.INJECTION_MIN_DISTINCT
    )
    criteria = {
        "injection_alive": bool(len(texts) and alive),
        "gap_not_below_zero": not bool(gap <= 0 and hi <= 0),  # recorded, never gating
    }
    gating = ["injection_alive"]
    check = {
        "n_cells": int(len(own)),
        "basis": basis,
        "differs_from_control": None if differs is None else float(differs),
        "n_control_greedies": len(control) if control else None,
        "distinct_pooled": float(distinct),
        "floor": C.INJECTION_MIN_DIFFERS_FROM_CONTROL if control else C.INJECTION_MIN_DISTINCT,
        # the re-read cosines: diagnostics, no floor
        "greedy_cos_own_mean": _mean(own),
        "greedy_cos_donor_mean": _mean(donor),
        "gap": float(gap),
        "gap_ci": [float(lo), float(hi)],
        "own_donor_direction_cos_mean": _mean(dcos),
        "n_fallback": int(n_fallback),
        "criteria": criteria,
        "gating": gating,
    }
    return check, all(criteria[k] for k in gating)


def injection_failure_message(check):
    """The abort message of a failed injection check."""
    failed = [k for k in check["gating"] if not check["criteria"][k]]
    if check["basis"] == BASIS_CONTROL:
        alive = (
            f"{check['differs_from_control']:.3f} of its greedies differ from every greedy of the "
            f"null-direction control (at least {check['floor']} required; a dead injection writes the control's)"
        )
    else:
        alive = (
            f"pooled distinct greedies {check['distinct_pooled']:.3f} (at least {check['floor']} required; "
            "the control is not in this invocation, and a dead injection decodes one prompt at every cell)"
        )
    return (
        f"injection check failed ({', '.join(failed)}) on {check['n_cells']} cells: {alive}; "
        f"diagnostics, gating nothing: own - donor {check['gap']:.3f}, 95% CI [{check['gap_ci'][0]:.3f}, "
        f"{check['gap_ci'][1]:.3f}], own re-read cosine "
        f"{check['greedy_cos_own_mean']:.3f}, cos(d_own, d_donor) {check['own_donor_direction_cos_mean']:.3f}"
    )


def failure_message(check, guards):
    """The abort message of whichever check the arm carries."""
    return injection_failure_message(check) if check is not None else null_failure_message(guards)


def distinctness_record(rows, texts):
    """The pooled and per-read-position shares of distinct greedy readouts (recorded for every arm)."""
    by_band = {}
    for (_r, _i, _p, band), t in zip(rows, texts):
        by_band.setdefault(band, []).append(t)
    return {
        "distinct_pooled": distinct_share(texts),
        "distinct_by_band": {b: distinct_share(ts) for b, ts in sorted(by_band.items())},
    }


# The share of one generation batch's greedies that must be its most common string.
NULL_MODAL_SHARE_MIN = 0.9


def refuse_unless_zero(arm, dirs):
    """The control's first check: the directions handed to the generator are exactly zero."""
    if np.asarray(dirs).any():
        raise RuntimeError(
            f"arm {arm!r} is the null-direction control and was handed a direction that is not zero at "
            f"{int(np.count_nonzero(np.any(np.asarray(dirs) != 0, axis=1)))} of its {len(dirs)} cells: it "
            "would read an activation, which is the one thing it claims not to do"
        )


def greedy_batch_of(rows, gen_chunk):
    """{(i, pos): the generation batch its greedy was decoded in}, named by the batch's first cell
    (`model_io.generate_batches` decodes the greedy pass in chunks of `gen_chunk` rows)."""
    return {
        (i, pos): "{}:{}".format(*rows[r - r % int(gen_chunk)][1:3])
        for r, (_row, i, pos, _band) in enumerate(rows)
    }


def greedy_batches(items, rows):
    by_cell = cell_records(items)
    return [(by_cell.get((i, p)) or {}).get("greedy_batch") for _r, i, p, _b in rows]


def batch_groups(rows, texts, batches):
    """{batch name: its greedy readouts}; a cell with no recorded batch is a group of its own."""
    groups = {}
    for (_r, i, p, _b), text, name in zip(rows, texts, batches or [None] * len(rows)):
        groups.setdefault(name or f"{i}:{p}", []).append(text)
    return groups


def modal_share(texts):
    counts = {}
    for t in texts:
        counts[t] = counts.get(t, 0) + 1
    return (max(counts.values()) / len(texts)) if texts else None


def null_verdict(rows, texts, batches=None):
    """The control's second check. Returns (check, ok). Within one `generate` call the control's rows are
    identical inputs, so at least NULL_MODAL_SHARE_MIN of each batch's greedies must be one string. Across
    batches nothing is asserted; the pooled shares are recorded."""
    rec = distinctness_record(rows, texts)
    groups = batch_groups(rows, texts, batches)
    shares = {name: modal_share(ts) for name, ts in sorted(groups.items())}
    rec["n_distinct_greedy"] = len({*texts})
    rec["modal_greedy_share"] = modal_share(texts)
    rec["n_batches"] = len(groups)
    rec["batch_modal_shares"] = shares
    rec["batches_below_floor"] = sorted(n for n, s in shares.items() if s < NULL_MODAL_SHARE_MIN)
    rec["reads_nothing"] = bool(texts) and not rec["batches_below_floor"]
    return rec, rec["reads_nothing"]


def null_failure_message(check):
    below = check["batches_below_floor"]
    worst = min((check["batch_modal_shares"][n] for n in below), default=float("nan"))
    return (
        f"the null-direction control is not reading nothing: {len(below)} of its {check['n_batches']} "
        f"generation batches decode to more than one greedy readout (the worst shares one string at "
        f"{worst:.2f} of its cells, at least {NULL_MODAL_SHARE_MIN} required) although the rows of a batch "
        f"are one prompt and one zero direction: {', '.join(below)}; the arm's file is written and the "
        "stage is NOT marked done"
    )


def null_dirs(n_rows, d_model=None):
    """The control's directions: an all-zero float32 array, one row per cell."""
    return np.zeros((int(n_rows), int(d_model or C.D_MODEL)), dtype=np.float32)


def generation_config(repo, revision):
    """A pinned checkpoint's shipped generation config, read without loading its weights."""
    from transformers import GenerationConfig

    return GenerationConfig.from_pretrained(repo, revision=revision)


def records(stop_ids):
    """`model_io.describe` bound to this pass's stop-token set."""
    from evals.downstream.common.model_io import describe

    return lambda gen_row, prompt_len, tok, max_new: describe(gen_row, prompt_len, tok, max_new, stop_ids)


def resume_view(cfg):
    """A saved file's generation-deciding fields (RESUME_FIELDS)."""
    return {f: cfg.get(f) for f in RESUME_FIELDS}


def resume_arm(doc, want, rows):
    """(cells, reason) for a saved arm file: {(i, pos): saved cell} when every field matches and the saved
    cells are a subset of `rows` (the rest is generated); else None and the field that differs."""
    cfg = doc.get("config") or {}
    view = resume_view(cfg)
    for f in RESUME_FIELDS:
        if view.get(f) != want[f]:
            return None, f
    saved = cell_records(doc.get("items") or [])
    mine = {(int(i), int(p)) for _r, i, p, _b in rows}
    if any(k not in mine for k in saved):
        return None, "cells"
    return saved, None


def cell_records(items):
    """(i, pos) -> the saved cell record, over a list of per-item rollout records."""
    return {(int(it["i"]), int(c["pos"])): c for it in items for c in it.get("cells") or []}


def cells_by_pos(doc, i):
    """{pos: cell} for one item of a saved rollout document."""
    it = next((x for x in (doc or {}).get("items", []) if x["i"] == i), None)
    return {c["pos"]: c for c in it["cells"]} if it else {}


def load_arm(run, arm):
    """One arm's merged readouts; a missing file raises."""
    rel = merged_rel(arm)
    if not run.exists(rel):
        raise RuntimeError(f"{rel} is missing — run the rollouts (and rollouts_merge) stage for arm {arm!r}")
    return run.read_json(rel)


def arm_scores(items, rows):
    """(own, donor, texts) of the greedies in `rows` order, or None when a greedy has no re-read cosine."""
    by_cell = cell_records(items)
    own, donor, texts = [], [], []
    for _r, i, p, _b in rows:
        g = (by_cell.get((i, p)) or {}).get("greedy") or {}
        if "cos_own" not in g or "cos_donor" not in g:
            return None
        own.append(float(g["cos_own"]))
        donor.append(float(g["cos_donor"]))
        texts.append(g.get("text") or "")
    return own, donor, texts


def greedy_texts(items, rows):
    by_cell = cell_records(items)
    return [((by_cell.get((i, p)) or {}).get("greedy") or {}).get("text") or "" for _r, i, p, _b in rows]


def control_greedies(arms):
    """Every greedy of the null control among `arms`, or None when the control is not among them."""
    if C.NULL_ARM not in arms:
        return None
    return [c["greedy"]["text"] or "" for c in cell_records(arms[C.NULL_ARM]).values() if c.get("greedy")]


def arm_records(arm, items, rows, dcos, n_fallback, control_texts=None):
    """(injection_check, guards, ok) for one arm over `rows`: the headline arm gets `injection_verdict`,
    the control `null_verdict`, the ablation its distinctness record and no verdict."""
    g = C.ARMS[arm]
    if g.get("null_direction"):
        guards, ok = null_verdict(rows, greedy_texts(items, rows), greedy_batches(items, rows))
        return None, guards, ok
    if g.get("untrained_base"):
        return None, distinctness_record(rows, greedy_texts(items, rows)), True
    scores = arm_scores(items, rows)
    if scores is None:
        raise RuntimeError(f"rollouts: arm {arm!r} has greedy readouts with no re-read cosine; regenerate it")
    own, donor, texts = scores
    check, ok = injection_verdict(own, donor, dcos, texts, control_texts, n_fallback)
    check.update(distinctness_record(rows, texts))
    return check, None, ok


def shard_doc(arm, items, want, check, guards, seconds, mu_norm=None, norm_filter=None):
    return {
        "config": {
            "arm": arm,
            **{k: want[k] for k in RESUME_FIELDS},
            "shard": [want["shard"], want["n_shards"]],
            "seed": want["seed_base"] + want["shard"],
            # null for an arm with no check of that kind
            "injection_check": check,
            "mu_norm": mu_norm,
            "guards": guards,
            "seconds": float(seconds),
            "norm_filter": norm_filter,
        },
        "items": items,
    }


def merge_shards_from(arm, docs, kept, table, n):
    """The merged arm document from `n` shard documents: every kept item exactly once with its read
    cells, in kept-item order, and the tallies pooled."""
    base = docs[0]["config"]
    for d in docs[1:]:
        for f in SHARD_AGREE_FIELDS:
            if resume_view(d["config"]).get(f) != resume_view(base).get(f):
                raise RuntimeError(
                    f"rollouts_merge: shard {d['config'].get('shard')} and shard {base.get('shard')} of arm "
                    f"{arm!r} disagree on {f!r}: they were generated by two different readers and must not "
                    "be pooled"
                )
    seen = {}
    for d in docs:
        for it in d["items"]:
            i = int(it["i"])
            if i in seen:
                raise RuntimeError(f"rollouts_merge: item i={i} appears in more than one shard of arm {arm!r}")
            seen[i] = it
    want_cells = {}
    for _r, i, p, _b in arm_rows(table, kept, arm):
        want_cells.setdefault(int(i), []).append(int(p))
    items = []
    for it in kept:
        i = int(it["i"])
        got = seen.pop(i, None)
        if got is None:
            raise RuntimeError(f"rollouts_merge: kept item i={i} is in no shard of arm {arm!r}")
        have = [int(c["pos"]) for c in got["cells"]]
        if have != want_cells.get(i, []):
            raise RuntimeError(
                f"rollouts_merge: arm {arm!r} item i={i} holds cells {have}, the read positions are "
                f"{want_cells.get(i)}"
            )
        items.append(got)
    if seen:
        raise RuntimeError(f"rollouts_merge: arm {arm!r} shards hold items not in the kept population: {sorted(seen)}")
    cfg = {
        k: v
        for k, v in base.items()
        if k not in ("shard", "seed", "guards", "seconds", "reused", "cells_reused", "cells_generated",
                     "norm_filter")
    }
    tallies = [d["config"].get("norm_filter") for d in docs]
    cfg.update(
        {
            "n_shards": n,
            "seeds": {str(int(d["config"]["shard"][0])): d["config"]["seed"] for d in docs},
            "seconds": float(sum(float(d["config"].get("seconds") or 0.0) for d in docs)),
            "norm_filter": norm_filter_record(dict.fromkeys(TALLY_KEYS, 0), *tallies) if any(tallies) else None,
        }
    )
    return {"config": cfg, "items": items}


def _new_cells(rows, samples, greedy, gen_chunk):
    """{(i, pos): cell record} for the rows this invocation generated."""
    batches = greedy_batch_of(rows, gen_chunk)
    return {
        (i, pos): {
            "pos": pos,
            "band": band,
            "greedy": greedy[r] if greedy else None,
            "greedy_batch": batches[(i, pos)] if greedy else None,
            "samples": samples[r],
        }
        for r, (_row, i, pos, band) in enumerate(rows)
    }


def _records(cells, rows, kept_mine):
    """The per-item records of one arm over `rows`; reused records pass through unchanged."""
    by_i = {}
    for _row, i, pos, _band in rows:
        by_i.setdefault(i, []).append(cells[(i, pos)])
    return [{"i": it["i"], "cells": by_i[it["i"]]} for it in kept_mine]


def record_name(arms, k, n):
    """The stage record of one invocation: `rollouts[.<arms>][.shard<k>of<n>]`."""
    return stage_record("rollouts" + arm_suffix("rollouts", arms), k, n)


def stage_rollouts(args, run):
    k, n = shard_of(args)
    chash = stage_key("rollouts", args, run)
    arms = [a for a in args.arms.split(",") if a]
    name = record_name(arms, k, n)
    if stage_done(run, name, chash) and not args.force:
        print(f"[rollouts:{k}of{n}] up to date")
        return
    started = time.time()
    from maemm.prompts import build_prompt_ids, marker_positions

    items_doc = run.read_json("data/items.json")
    kept = [x for x in items_doc["items"] if not x["excluded"]]
    # the cell table with the synthetic mean rows appended (row indices into `load_h`)
    table = M.full_table(run)
    drows, n_donor_fallback = donor_row_map(kept, table)
    # The resume decision needs only files and a tokenizer; no weights are loaded before it.
    tok = load_tokenizer()
    prompt_ids, mpos = build_prompt_ids(tok)
    assert marker_positions(tok, prompt_ids) == mpos and len(mpos) == 1
    # Both models must ship the same decoding config; every arm is cut at the base's stop ids.
    from evals.downstream.common.model_io import refuse_unless_generation_agrees, stop_token_ids

    base_gen = generation_config(C.MODEL, C.MODEL_REVISION)
    refuse_unless_generation_agrees(base_gen, generation_config(C.INVERTER, C.INVERTER_REVISION))
    stops = stop_token_ids(tok, base_gen)
    describe_fn = records(stops)
    plans, base, inverter, dirs = {}, None, None, None
    for arm in arms:
        g = C.ARMS[arm]
        rows = shard_rows(arm_rows(table, kept, arm), k, n)
        want = {
            "model": [C.MODEL, C.MODEL_REVISION],
            "inverter": None if g.get("untrained_base") else [C.INVERTER, C.INVERTER_REVISION],
            "prompt_ids": [int(t) for t in prompt_ids],
            "marker_pos": mpos[0],
            "gen": dict(g),
            "seed_base": arm_seed(arm, args.seed),
            "reread_norm_filter": C.REREAD_NORM_FILTER,
            "upstream": dict(chash.upstream),
            "shard": k,
            "n_shards": n,
        }
        rel = shard_rel(arm, k, n) if n > 1 else merged_rel(arm)
        cells, seconds, prior_tally = {}, 0.0, None
        if run.exists(rel) and not args.force:
            saved = run.read_json(rel)
            cells, reason = resume_arm(saved, want, rows)
            if cells is None:
                print(f"[rollouts:{arm}] {rel} exists but its config {reason!r} differs; regenerating", flush=True)
                cells = {}
            else:
                seconds = float((saved.get("config") or {}).get("seconds") or 0.0)
                prior_tally = (saved.get("config") or {}).get("norm_filter")
        missing = [x for x in rows if (x[1], x[2]) not in cells]
        plans[arm] = {
            "want": want,
            "rel": rel,
            "rows": rows,
            "cells": cells,
            "missing": missing,
            "reused": bool(cells) and not missing,
            "n_reused": len(cells),
            "seconds": seconds,
            "prior_tally": prior_tally,
            "tally": new_filter_stats(),
        }
    mu_norm = None
    if any(not C.ARMS[a].get("null_direction") for a in arms):
        from evals.downstream.common.model_io import direction

        H = M.load_h(run)
        mu = BG.load_centring_mean()
        dirs = np.stack([direction(H[r], mu) for r in range(len(table))])
        mu_norm = float(np.linalg.norm(mu))
    # Every arm generates first, then the inverter is freed and the re-reads run on the base.
    generating = [a for a in arms if plans[a]["missing"]]
    if generating:
        from evals.downstream.common.model_io import free_model, generate_injected, load_base, load_inverter

        if any(not C.ARMS[a].get("null_direction") for a in generating):
            base, _tok = load_base(args.device, C.MODEL, C.MODEL_REVISION)
        try:
            if any(not C.ARMS[a].get("untrained_base") for a in generating):
                inverter = load_inverter(args.device, C.INVERTER, C.INVERTER_REVISION)
            for arm in generating:
                plan, g = plans[arm], C.ARMS[arm]
                t0 = time.time()
                # Only the cells the saved file lacks, each seeded by its place in the shard's rows.
                gen_rows = plan["missing"]
                place = {(i, p): r for r, (_row, i, p, _b) in enumerate(plan["rows"])}
                idx = np.asarray([r for r, _i, _p, _b in gen_rows], dtype=int)
                arm_dirs = null_dirs(len(gen_rows)) if g.get("null_direction") else dirs[idx]
                if g.get("null_direction"):
                    refuse_unless_zero(arm, arm_dirs)
                plan["samples"], plan["greedy"] = generate_injected(
                    base if g.get("untrained_base") else inverter,
                    tok,
                    arm_dirs,
                    prompt_ids,
                    mpos[0],
                    args.device,
                    n_samples=g["n_samples"],
                    seed=shard_seed(arm, k, args.seed),
                    greedy=g["greedy"],
                    gen_chunk=C.GEN_CHUNK,
                    sampling={x: g[x] for x in ("temp", "top_p", "top_k", "min_p", "max_new", "min_new")},
                    inject_layer=C.INJECT_LAYER,
                    steer_coeff=C.STEER_COEFF,
                    describe_fn=describe_fn,
                    row_ids=[place[(i, p)] for _row, i, p, _b in gen_rows],
                )
                plan["new_seconds"] = time.time() - t0
        finally:
            if inverter is not None:
                inverter = free_model(inverter)
    # The control first: the headline arm's check reads the control's greedies.
    done, failed = {}, []
    for arm in sorted(arms, key=lambda a: not C.ARMS[a].get("null_direction")):
        plan, g = plans[arm], C.ARMS[arm]
        rows = plan["rows"]
        dcos = direction_cos(dirs, drows, rows) if dirs is not None else np.zeros(len(rows))
        if plan["missing"]:
            from evals.downstream.common.model_io import reread_cos

            gen_rows = plan["missing"]
            greedy = plan.pop("greedy")
            if not (g.get("null_direction") or g.get("untrained_base")):
                t0 = time.time()
                idx = np.asarray([r for r, _i, _p, _b in gen_rows], dtype=int)
                texts = [x["text"] for x in greedy]
                donor_idx = np.asarray([drows[(i, p)] for _r, i, p, _b in gen_rows], dtype=int)
                # Unfiltered; the own-direction pass fills the norm-filter tally.
                own = reread_cos(texts, dirs[idx], base, tok, args.device, max_length=C.REREAD_MAX_LENGTH,
                                 stats=plan["tally"])
                donor = reread_cos(texts, dirs[donor_idx], base, tok, args.device,
                                   max_length=C.REREAD_MAX_LENGTH)
                for r, x in enumerate(greedy):
                    x["cos_own"], x["cos_donor"] = float(own[r]), float(donor[r])
                plan["new_seconds"] += time.time() - t0
            plan["cells"].update(_new_cells(gen_rows, plan.pop("samples"), greedy, C.GEN_CHUNK))
            plan["seconds"] += plan["new_seconds"]
        kept_mine = [it for it in kept if it["i"] in {i for _r, i, _p, _b in rows}]
        plan["items"] = done[arm] = _records(plan["cells"], rows, kept_mine)
        check, guards, ok = arm_records(
            arm, plan["items"], rows, dcos, n_donor_fallback, control_greedies(done)
        )
        doc = shard_doc(
            arm,
            plan["items"],
            plan["want"],
            check,
            guards,
            plan["seconds"],
            mu_norm=None if g.get("null_direction") else mu_norm,
            norm_filter=None if (g.get("null_direction") or g.get("untrained_base"))
            else norm_filter_record(plan["tally"], plan["prior_tally"]),
        )
        if n == 1:
            # --n-shards 1 is its own merge.
            doc = merge_shards_from(arm, [doc], kept, table, 1)
            doc["config"]["injection_check"], doc["config"]["guards"] = check, guards
        plan["norm_filter"] = doc["config"]["norm_filter"]
        if plan["reused"]:
            doc["config"]["reused"] = True
        doc["config"]["cells_reused"] = plan["n_reused"]
        doc["config"]["cells_generated"] = len(plan["missing"])
        run.write_json(plan["rel"], doc)
        write_provenance(
            run,
            {
                f"rollouts_{arm}_shard{k}of{n}": {
                    "injection_check": check,
                    "guards": guards,
                    "seed": shard_seed(arm, k, args.seed),
                    "n_items": len(plan["items"]),
                    "n_cells": len(rows),
                    "n_cells_reused": plan["n_reused"],
                    "n_cells_generated": len(plan["missing"]),
                    "seconds": plan["seconds"],
                    "new_seconds": plan.get("new_seconds", 0.0),
                    "reused": plan["reused"],
                }
            },
            stage=provenance_stage("rollouts", k, n, arms),
        )
        print(
            f"[rollouts:{arm}:{k}of{n}] {'reused ' if plan['reused'] else ''}{plan['rel']}: "
            f"{len(plan['items'])} items x {len(rows)} cells x {g['n_samples']}"
            f"{'+greedy' if g['greedy'] else ''} ({plan['n_reused']} cells reused, "
            f"{len(plan['missing'])} generated in {plan.get('new_seconds', 0.0):.0f}s); check {check}",
            flush=True,
        )
        if not ok:
            failed.append((arm, check, guards))
    # The abort comes after every arm's file is written; the stage is not marked done.
    if failed:
        raise RuntimeError("; ".join(f"arm {a}: {failure_message(c, g)}" for a, c, g in failed))
    mark_stage(
        run,
        name,
        chash,
        {
            "arms": arms,
            "shard": [k, n],
            "stop_token_ids": list(stops),
            "n_cells": {a: len(plans[a]["rows"]) for a in arms},
            "cells_reused": {a: plans[a]["n_reused"] for a in arms},
            "cells_generated": {a: len(plans[a]["missing"]) for a in arms},
            "reused": {a: bool(plans[a]["reused"]) for a in arms},
            "norm_filter": {a: plans[a]["norm_filter"] for a in arms},
            "generation_seconds": {a: float(plans[a]["seconds"]) for a in arms},
            "new_generation_seconds": {a: float(plans[a].get("new_seconds", 0.0)) for a in arms},
        },
        started=started,
    )


def merge_shards(run, arm, n):
    missing = [shard_rel(arm, i, n) for i in range(n) if not run.exists(shard_rel(arm, i, n))]
    if missing:
        raise RuntimeError(f"rollouts_merge: {len(missing)} of {n} shard files are missing: {', '.join(missing)}")
    docs = [run.read_json(shard_rel(arm, i, n)) for i in range(n)]
    kept = [x for x in run.read_json("data/items.json")["items"] if not x["excluded"]]
    return merge_shards_from(arm, docs, kept, M.full_table(run), n)


def _run_level_records(run, arm, doc, control_texts=None):
    """The arm's check over the whole run from the merged cells: the merge is the first place the
    headline arm and the control are in one process."""
    kept = [x for x in run.read_json("data/items.json")["items"] if not x["excluded"]]
    table = M.full_table(run)
    rows = arm_rows(table, kept, arm)
    drows, n_fallback = donor_row_map(kept, table)
    dcos = np.zeros(len(rows))
    if not (C.ARMS[arm].get("null_direction") or C.ARMS[arm].get("untrained_base")):
        from evals.downstream.common.model_io import direction

        H = M.load_h(run)
        mu = BG.load_centring_mean()
        dcos = direction_cos(np.stack([direction(H[r], mu) for r in range(len(table))]), drows, rows)
    return arm_records(arm, doc["items"], rows, dcos, n_fallback, control_texts)


def refuse_another_captures_arm(run, args, arm, doc):
    """Raise when an arm file was generated over other upstream records than the directory now holds."""
    want = dict(stage_key("rollouts", args, run).upstream)
    got = (doc.get("config") or {}).get("upstream")
    if got != want and not args.force:
        raise RuntimeError(
            f"rollouts_merge: {merged_rel(arm)} was generated over upstream records {got}, and this "
            f"directory's now read {want}; run `rollouts --arms {arm}` again before merging"
        )


def stage_rollouts_merge(args, run):
    n = int(getattr(args, "n_shards", 1) or 1)
    chash = stage_key("rollouts_merge", args, run, n_shards=n)
    if stage_done(run, "rollouts_merge", chash) and not args.force:
        print("[rollouts_merge] up to date")
        return
    started = time.time()
    arms = [a for a in args.arms.split(",") if a]
    docs, merged = {}, set()
    for arm in arms:
        have_shards = any(run.exists(shard_rel(arm, i, n)) for i in range(n))
        if run.exists(merged_rel(arm)) and not have_shards:
            # the --n-shards 1 path already wrote the merged file
            docs[arm] = run.read_json(merged_rel(arm))
            print(f"[rollouts_merge:{arm}] {merged_rel(arm)} was written by a single-shard run: nothing to merge")
        else:
            docs[arm] = merge_shards(run, arm, n)
            merged.add(arm)
        refuse_another_captures_arm(run, args, arm, docs[arm])
    control = control_greedies({a: d["items"] for a, d in docs.items()})
    out, failed = {}, []
    for arm in arms:
        doc = docs[arm]
        # Re-evaluated against the control; rewritten only where the record moved.
        check, guards, ok = _run_level_records(run, arm, doc, control)
        was = (doc["config"].get("injection_check"), doc["config"].get("guards"))
        doc["config"]["injection_check"], doc["config"]["guards"] = check, guards
        if arm in merged or was != (check, guards):
            run.write_json(merged_rel(arm), doc)
        if not ok:
            failed.append((arm, check, guards))
        cfg = doc["config"]
        out[arm] = {
            "n_items": len(doc["items"]),
            "n_cells": sum(len(it["cells"]) for it in doc["items"]),
            "injection_check": cfg.get("injection_check"),
            "guards": cfg.get("guards"),
        }
        print(
            f"[rollouts_merge:{arm}] {out[arm]['n_items']} items, {out[arm]['n_cells']} cells over "
            f"{n} shard(s); check {cfg.get('injection_check')}; guards {cfg.get('guards')}",
            flush=True,
        )
    write_provenance(run, {"rollouts_arms": out}, stage="rollouts_merge")
    if failed:
        raise RuntimeError("; ".join(f"arm {a}: {failure_message(c, g)}" for a, c, g in failed))
    mark_stage(run, "rollouts_merge", chash, {"arms": out, "n_shards": n}, started=started)
